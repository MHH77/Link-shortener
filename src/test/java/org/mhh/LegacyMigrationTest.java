package org.mhh;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.FlywayException;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import java.nio.file.Path;
import java.sql.DriverManager;
import static org.junit.jupiter.api.Assertions.*;

class LegacyMigrationTest {
    @TempDir Path directory;

    @Test void requiresOptInAndPreservesExistingLinksAcrossRestarts() throws Exception {
        String url = "jdbc:h2:file:" + directory.resolve("legacy");
        try (var db = DriverManager.getConnection(url, "sa", ""); var sql = db.createStatement()) {
            sql.execute("create table url(id bigint generated by default as identity primary key, " +
                    "short_code varchar(255) unique, original_url varchar(2048), click_count integer not null, " +
                    "expiration_date timestamp with time zone)");
            sql.execute("insert into url(short_code, original_url, click_count) values('abc','https://example.org/',17)");
        }
        Flyway normal = Flyway.configure().dataSource(url, "sa", "").load();
        assertThrows(FlywayException.class, normal::migrate);
        Flyway.configure().dataSource(url, "sa", "").baselineOnMigrate(true).baselineVersion("1").load().migrate();
        assertEquals(0, normal.migrate().migrationsExecuted);
        try (var db = DriverManager.getConnection(url, "sa", ""); var sql = db.createStatement();
             var row = sql.executeQuery("select original_url, click_count, management_token_hash, moderation_state from url where short_code='abc'")) {
            assertTrue(row.next());
            assertEquals("https://example.org/", row.getString(1));
            assertEquals(17, row.getInt(2));
            assertNull(row.getString(3));
            assertNull(row.getString(4));
        }
    }
}
